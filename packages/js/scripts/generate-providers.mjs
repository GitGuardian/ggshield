/**
 * Convert the single-source `providers/*.yaml` contract into the JS module
 * `src/providers.generated.js`.
 *
 * The repo-root `providers/` directory is the only committed copy; this module
 * is generated at build time (the `prepare`/`prepack` scripts) and gitignored,
 * so the package never carries a second committed copy — mirroring the Python
 * SDK's build-time vendoring. Parsing goes through the same strict
 * {@link parseProviderDef} the tests use, so the artifact can only ever hold a
 * validated definition and the runtime imports plain data with zero
 * dependencies (the `yaml` parser stays a devDependency).
 */

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { parse as parseYaml } from "yaml";
import { parseProviderDef } from "../src/definition.js";

const PROVIDERS_DIR = new URL("../../../providers/", import.meta.url);
const OUTPUT_FILE = new URL("../src/providers.generated.js", import.meta.url);

/**
 * Build the `{ [name]: ProviderDef }` map from the YAML contract.
 *
 * @returns {Record<string, import('../src/definition.js').ProviderDef>}
 */
function loadDefinitions() {
  const files = readdirSync(PROVIDERS_DIR)
    .filter((name) => name.endsWith(".yaml"))
    .toSorted();
  /** @type {Record<string, import('../src/definition.js').ProviderDef>} */
  const definitions = {};
  for (const file of files) {
    const text = readFileSync(new URL(file, PROVIDERS_DIR), "utf8");
    const def = parseProviderDef(parseYaml(text));
    definitions[def.name] = def;
  }
  return definitions;
}

/**
 * Render the generated module source.
 *
 * @param {Record<string, import('../src/definition.js').ProviderDef>} definitions
 * @returns {string}
 */
function render(definitions) {
  const literal = JSON.stringify(definitions, null, 2);
  return `// Code generated by scripts/generate-providers.mjs from providers/*.yaml.
// Generated at build time and gitignored — do not commit or edit by hand.
// Regenerate with \`pnpm run generate:providers\`.

/** @typedef {import('./definition.js').ProviderDef} ProviderDef */

/**
 * Recursively freeze a value so the shared definitions cannot be mutated.
 *
 * @param {unknown} value
 * @returns {void}
 */
function deepFreeze(value) {
  if (value !== null && typeof value === 'object') {
    for (const property of Object.values(value)) {
      deepFreeze(property);
    }
    Object.freeze(value);
  }
}

/** @type {Record<string, ProviderDef>} */
export const PROVIDER_DEFINITIONS = ${literal};

deepFreeze(PROVIDER_DEFINITIONS);
`;
}

writeFileSync(OUTPUT_FILE, render(loadDefinitions()));
